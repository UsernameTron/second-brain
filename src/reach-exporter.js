'use strict';

/**
 * reach-exporter.js
 *
 * v1.6 SURFACE-REACH-01 (ADR-018/ADR-019): cross-surface reach layer.
 *
 * Plants a pointer + capped-digest cache file (`second-brain.md`) into an
 * explicit allowlist of Claude Code auto-memory directories, so every surface
 * on this machine discovers that memory.md is the canonical memory store and
 * can query it live. The file is regenerated wholesale on every promotion —
 * it never accumulates, so drift is bounded by the last promotion run.
 *
 * Boundary guarantees:
 *   - Reads ONLY memory/memory.md (RIGHT side) via memory-reader. LEFT is
 *     never touched by construction.
 *   - Every digest entry re-passes the content-policy exclusion gate at
 *     egress, FAIL-CLOSED (BLOCK or error → entry excluded). Required because
 *     the extraction→staging path bypasses the ingress gate, so memory.md
 *     content is not guaranteed clean.
 *   - Never creates directories in foreign projects: a missing target is
 *     skipped with a reason, not created.
 *
 * @module reach-exporter
 */

const fs = require('fs');
const os = require('os');
const path = require('path');

const { readMemory } = require('./memory-reader');
const { checkContent } = require('./content-policy');
const { loadExcludedTerms } = require('./pipeline-infra');

const REACH_FILE_NAME = 'second-brain.md';
const INDEX_FILE_NAME = 'MEMORY.md';
const INDEX_LINE = `- [Second Brain (canonical memory)](${REACH_FILE_NAME}) — pointer + digest cache generated by the second-brain reach exporter; the canonical store wins`;

const VAULT_ROOT = () => process.env.VAULT_ROOT || path.join(process.env.HOME, 'Claude Cowork');
const REPO_PATH = path.resolve(__dirname, '..');

function loadReachConfig() {
  const CONFIG_DIR = process.env.CONFIG_DIR_OVERRIDE || path.join(__dirname, '..', 'config');
  const raw = fs.readFileSync(path.join(CONFIG_DIR, 'reach-targets.json'), 'utf8');
  return JSON.parse(raw);
}

function expandHome(p) {
  if (p === '~') return os.homedir();
  if (p.startsWith('~/')) return path.join(os.homedir(), p.slice(2));
  return p;
}

function logReach(event, detail) {
  process.stderr.write(JSON.stringify({ module: 'reach-exporter', event, ...detail }) + '\n');
}

/**
 * Render the pointer + digest reach file (Claude Code auto-memory format:
 * YAML frontmatter + markdown body).
 * @param {Array<{date: string, category: string, content: string}>} entries - Gated digest entries, newest first.
 * @param {{generatedAt: string, vaultRoot: string, repoPath: string}} meta - Render context.
 * @returns {string} Full file content.
 */
function renderReachFile(entries, { generatedAt, vaultRoot, repoPath }) {
  const memoryPath = path.join(vaultRoot, 'memory', 'memory.md');
  const recallPath = path.join(repoPath, 'scripts', 'recall.js');

  const digest = entries.length > 0
    ? entries.map(e => `- **${e.date} · ${e.category}** — ${e.content}`).join('\n')
    : '_(no entries passed the exclusion gate)_';

  return `---
name: second-brain-reach
description: Pointer to the canonical second-brain memory system plus a digest of recent promoted memories (generated cache — canonical store wins)
metadata:
  type: reference
---

# Second Brain — canonical memory system (generated cache)

> **This file is a generated cache. On any conflict, the canonical store wins.**
> Generated: ${generatedAt} — regenerated on every memory promotion. Do not edit; edits are overwritten.

**Canonical store:** \`${memoryPath}\` — the compounding memory layer owned by the
second-brain project at \`${repoPath}\` (see \`decisions/ADR-018-cross-surface-reach.md\`
and \`decisions/ADR-019-reach-layer-mechanism.md\` there). Do not design or build a new
memory system — one is already running; query it instead.

**Query it live from any session on this machine:**

\`\`\`bash
node ${recallPath} "<query>" --hybrid --top 5
\`\`\`

Flags: \`--category <name>\`, \`--since YYYY-MM-DD\`, \`--top N\`, \`--semantic\`, \`--hybrid\` (falls back to keyword search when embeddings are unavailable).

## Recent promoted memories (${entries.length} most recent, exclusion-gated)

${digest}
`;
}

/**
 * Idempotently upsert the reach line in a target's MEMORY.md index:
 * an existing line linking to second-brain.md is replaced in place,
 * otherwise the line is appended. Creates MEMORY.md if absent.
 * @param {string} targetDir - The auto-memory directory.
 */
function updateIndexFile(targetDir) {
  const indexPath = path.join(targetDir, INDEX_FILE_NAME);
  let content;
  try {
    content = fs.readFileSync(indexPath, 'utf8');
  } catch (_) {
    content = '# Memory Index\n';
  }
  const lines = content.split('\n');
  const existing = lines.findIndex(l => l.includes(`](${REACH_FILE_NAME})`));
  if (existing >= 0) {
    lines[existing] = INDEX_LINE;
  } else {
    while (lines.length > 0 && lines[lines.length - 1].trim() === '') lines.pop();
    lines.push(INDEX_LINE);
  }
  fs.writeFileSync(indexPath, lines.join('\n') + '\n', 'utf8');
}

/**
 * Run the reach export: read memory.md, gate the newest entries through the
 * exclusion policy (fail-closed), render the pointer + digest file, and write
 * it (plus an index line) into each configured target directory. Per-target
 * failures are reported, never thrown.
 * Target resolution precedence: options.targets → REACH_TARGETS_OVERRIDE env
 * (colon-separated; empty string = no targets — the test-isolation hatch so
 * suites exercising promotion never write into real auto-memory dirs) →
 * config targets.
 * @param {Object} [options] - Export options.
 * @param {string[]} [options.targets] - Override target dirs (used by tests); defaults to env/config.
 * @param {number} [options.digestMax] - Override digest cap; defaults to config.
 * @returns {Promise<{success: boolean, disabled?: boolean, error?: string, targets: Array<{dir: string, status: 'written'|'skipped', reason?: string}>, included: number, excluded: number}>} Export outcome.
 */
async function runReachExport(options = {}) {
  let config;
  try {
    config = loadReachConfig();
  } catch (err) {
    return { success: false, error: 'Failed to load reach-targets config: ' + err.message, targets: [], included: 0, excluded: 0 };
  }

  if (config.enabled === false) {
    return { success: true, disabled: true, targets: [], included: 0, excluded: 0 };
  }

  const digestMax = options.digestMax !== undefined ? options.digestMax : config.digestMax;
  const envOverride = process.env.REACH_TARGETS_OVERRIDE;
  const rawTargets = options.targets !== undefined
    ? options.targets
    : envOverride !== undefined
      ? (envOverride === '' ? [] : envOverride.split(':'))
      : config.targets;
  const targetDirs = rawTargets.map(expandHome);

  let entries;
  try {
    entries = await readMemory();
  } catch (err) {
    return { success: false, error: 'Failed to read memory.md: ' + err.message, targets: [], included: 0, excluded: 0 };
  }

  // Newest first: sort by header date, then added timestamp. memory.md is
  // prepend-ordered already; the sort makes recency explicit and stable.
  entries.sort((a, b) => {
    if (a.date !== b.date) return a.date < b.date ? 1 : -1;
    if (a.addedAt !== b.addedAt) return a.addedAt < b.addedAt ? 1 : -1;
    return 0;
  });

  // loadExcludedTerms never throws — it returns [] on any load failure,
  // matching the gate semantics used by vault-gateway.
  const excludedTerms = loadExcludedTerms();

  const digest = [];
  let excluded = 0;
  for (const entry of entries) {
    if (digest.length >= digestMax) break;
    try {
      // Gate what will actually be rendered (category + content), fail-closed.
      const verdict = await checkContent(`${entry.category} ${entry.content}`, excludedTerms);
      if (verdict.decision === 'PASS') {
        digest.push(entry);
      } else {
        excluded++;
        logReach('entry-excluded', { reason: verdict.reason || 'policy block' });
      }
    } catch (err) {
      // checkContent is fail-closed internally, but stay closed on any throw too.
      excluded++;
      logReach('entry-excluded', { reason: 'gate error: ' + err.message });
    }
  }

  const rendered = renderReachFile(digest, {
    generatedAt: new Date().toISOString(),
    vaultRoot: VAULT_ROOT(),
    repoPath: REPO_PATH,
  });

  const targets = [];
  for (const dir of targetDirs) {
    if (!fs.existsSync(dir)) {
      targets.push({ dir, status: 'skipped', reason: 'target directory does not exist' });
      logReach('target-skipped', { dir, reason: 'missing' });
      continue;
    }
    try {
      fs.writeFileSync(path.join(dir, REACH_FILE_NAME), rendered, 'utf8');
      updateIndexFile(dir);
      targets.push({ dir, status: 'written' });
      logReach('target-written', { dir });
    } catch (err) {
      targets.push({ dir, status: 'skipped', reason: err.message });
      logReach('target-skipped', { dir, reason: err.message });
    }
  }

  return { success: true, targets, included: digest.length, excluded };
}

module.exports = { runReachExport, renderReachFile, updateIndexFile };
