#!/usr/bin/env node
'use strict';
// Captures the CURRENT rendered roster prompts to server/config/
// legacy-roster-prompts.json — the byte-for-byte "previous template" that
// reseedRosterPrompts() matches against to decide whether a live agent was
// hand-edited before adopting a changed prompt.
//
// Workflow to change a roster prompt:
//   1. node scripts/snapshot-roster-prompts.js   (captures the about-to-be-old text)
//   2. edit the prompt in server/roster.js
//   3. bump RESEED_KEY (seed_roster_prompts_vN) in server/roster.js
//
// Only ONE predecessor is kept, so the chain assumes every release actually
// boots: a workspace that skips a release never matches the newer snapshot,
// gets no update, and has the key marked done. Fine for a single Cloud Run
// service deployed in order; if this ever ships to workspaces that can skip
// versions, keep an ordered list of snapshots instead.
//
// Requiring roster.js only DEFINES the roster; it does not seed (that is
// index.js), so this is safe to run against the working tree.

const fs = require('node:fs');
const path = require('node:path');
const { ROSTER_AGENTS } = require('../server/roster');

const out = {
  _comment: 'Rendered roster system_prompts as of the last snapshot, matched byte-for-byte by reseedRosterPrompts() to decide whether a live agent was hand-edited. Generated by scripts/snapshot-roster-prompts.js — do not hand-edit.',
  prompts: Object.fromEntries(ROSTER_AGENTS.map((a) => [a.name, a.system_prompt])),
};
const dest = path.join(__dirname, '..', 'server', 'config', 'legacy-roster-prompts.json');
fs.writeFileSync(dest, `${JSON.stringify(out, null, 2)}\n`);
process.stdout.write(`snapshot written: ${Object.keys(out.prompts).length} prompts → ${path.relative(process.cwd(), dest)}\n`);
